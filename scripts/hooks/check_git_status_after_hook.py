"""check_git_status_after_hook.py — Detect MM state after hooks have run (v8.4 N105).

Background (failure mode N105, 2026-06-15):

When a pre-commit hook modifies a file that the user already staged
with `git add`, the file ends up in the `MM` state (modified in
both the index and the working tree). The pre-commit framework
re-stages the working tree after each hook, but it does NOT
automatically `git add` the hook's changes. As a result, the
`git commit` operation that the framework eventually issues sees
the staged version (not the hook's version) and rolls the file
back, while the working tree keeps the hook's version. This
manifests as the dreaded "files were modified by this hook" error.

Symptoms that this script catches:

- `MM` — staged AND work tree modified (most common; the
  classic N105 case where `gaf-sync` clobbered an auto-maintained
  file the user just regenerated).
- `MD` — staged AND work tree deleted (a hook deleted a staged
  file).
- `AM` — added in index AND work tree modified (a hook touched a
  newly-added file).
- `AD` — added in index AND work tree deleted (a hook deleted a
  newly-added file).

Exit codes:

- 0 — no hook-induced modifications; safe to commit.
- 1 — at least one file is in MM/MD/AM/AD state; commit blocked
       with a clear remediation hint.
- 2 — invocation error (not a git repo, git binary missing, etc.).

Usage:

    python check_git_status_after_hook.py            # strict, blocks on MM
    python check_git_status_after_hook.py --warn-only  # report but don't block
    python check_git_status_after_hook.py --auto-only  # only check known auto-maintained files

Hook registration (.pre-commit-config.yaml):

    - id: gaf-git-status-check
      name: GAF git status post-hook check (N105)
      entry: python scripts/hooks/check_git_status_after_hook.py
      language: system
      pass_filenames: false
      always_run: true
      stages: [pre-commit]

The hook should be declared LAST in the local hooks list so it
runs after every other hook has had a chance to (mis)modify the
working tree.
"""
from __future__ import annotations

# Bootstrap: make scripts/ importable when this file lives in a subdir.
import sys as _sys
from pathlib import Path as _Path

